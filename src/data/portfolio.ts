const localize = (value: LocalizedText, locale: Locale) => value[locale];

function localizeExperiences(locale: Locale): Experience[] {
  return portfolioSource.experiences.map((experience) => ({
    id: experience.id,
    company: experience.company,
    role: localize(experience.role, locale),
    period: localize(experience.period, locale),
    mission: localize(experience.mission, locale),
    environment: [...experience.environment],
    contributions: experience.contributions.map((item) => localize(item, locale)),
  }));
}

function localizeProjects(locale: Locale): Project[] {
  return portfolioSource.projects.map((project) => ({
    id: project.id,
    priority: project.priority,
    status: localize(project.status, locale),
    title: localize(project.title, locale),
    subtitle: localize(project.subtitle, locale),
    problem: localize(project.problem, locale),
    architecture: localize(project.architecture, locale),
    role: localize(project.role, locale),
    outcome: { kind: project.outcome.kind, text: localize(project.outcome.text, locale) },
    technologies: [...project.technologies],
    details: project.details?.map((item) => localize(item, locale)) ?? [],
    links: project.links.map((link) => ({ label: localize(link.label, locale), url: link.url })),
  }));
}

function localizeTechnologyDomains(locale: Locale): TechnologyDomain[] {
  return portfolioSource.technologyDomains.map((domain) => ({
    id: domain.id,
    label: localize(domain.label, locale),
    description: localize(domain.description, locale),
    technologies: [...domain.technologies],
  }));
}

function localizeCertifications(locale: Locale): Certification[] {
  return portfolioSource.certifications.map((certification) => ({
    id: certification.id,
    title: certification.title,
    provider: certification.provider,
    date: localize(certification.date, locale),
    verifyLabel: localize(certification.verifyLabel, locale),
    url: certification.url,
  }));
}

function localizeEducation(locale: Locale): Education[] {
  return portfolioSource.education.map((education) => ({
    id: education.id,
    degree: localize(education.degree, locale),
    school: localize(education.school, locale),
    period: localize(education.period, locale),
    location: localize(education.location, locale),
    domains: education.domains.map((domain) => localize(domain, locale)),
  }));
}

function localizeResumes(locale: Locale): ResumeSet {
  const [primary, ...alternates] = portfolioSource.resumes.map((resume) => ({
    id: resume.id,
    label: localize(resume.label, locale),
    url: resume.urls[locale],
  }));

  return { primary, alternates };
}

export function getPortfolio(locale: Locale): LocalizedPortfolio {
  const { identity, hero, about, contact } = portfolioSource;

  return {
    identity: {
      name: identity.name,
      title: localize(identity.title, locale),
      shortTitle: localize(identity.shortTitle, locale),
      description: localize(identity.description, locale),
      availability: localize(identity.availability, locale),
      location: localize(identity.location, locale),
      languages: localize(identity.languages, locale),
      email: identity.email,
      phoneDisplay: identity.phoneDisplay,
      phoneHref: identity.phoneHref,
      portrait: identity.portrait,
      github: identity.github,
      linkedin: identity.linkedin,
    },
    navigation: portfolioSource.navigation.map((item) => ({ id: item.id, label: localize(item.label, locale) })),
    hero: {
      disciplines: hero.disciplines.map((discipline) => localize(discipline, locale)),
      actions: {
        projects: localize(hero.actions.projects, locale),
        infrastructure: localize(hero.actions.infrastructure, locale),
        contact: localize(hero.actions.contact, locale),
      },
      facts: hero.facts.map((fact) => ({ value: fact.value, label: localize(fact.label, locale) })),
    },
    about: {
      heading: localize(about.heading, locale),
      profileLabel: localize(about.profileLabel, locale),
      paragraphs: about.paragraphs.map((paragraph) => localize(paragraph, locale)),
    },
    expertise: portfolioSource.expertise.map((item) => ({
      id: item.id,
      title: localize(item.title, locale),
      description: localize(item.description, locale),
      capabilities: item.capabilities.map((capability) => localize(capability, locale)),
    })),
    technologyDomains: localizeTechnologyDomains(locale),
    experiences: localizeExperiences(locale),
    projects: localizeProjects(locale),
    certifications: localizeCertifications(locale),
    education: localizeEducation(locale),
    resumes: localizeResumes(locale),
    labels: Object.fromEntries(
      Object.entries(portfolioSource.labels).map(([key, value]) => [key, localize(value, locale)]),
    ),
    contact: {
      heading: localize(contact.heading, locale),
      subheading: localize(contact.subheading, locale),
      terminalCommand: contact.terminalCommand,
      terminalStatus: localize(contact.terminalStatus, locale),
    },
  };
}
